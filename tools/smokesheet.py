#!/usr/bin/env python3
"""Write src/client/cl_smokesheet.qc: the frames of the two smoke sheets Source's env_fire uses.

    python tools/smokesheet.py <game>_dir.vpk [more...] > src/client/cl_smokesheet.qc

particles/fire_01.pcf draws env_fire_tiny_smoke and _small_smoke through
particle/smoke1/smoke1.vmt, and _medium_smoke, _large_smoke and _large_smoke_b through
particle/vistasmokev1/vistasmokev1.vmt.  Their sheets (VTF resource 0x10) are read with
tools/vtfsheet.py out of each .vpk given that carries them (Half-Life 2's
hl2_textures_dir.vpk, Counter-Strike: Source's cstrike_pak_dir.vpk).  Nothing of either
image is copied; one colour is MEASURED off vistasmokev1 (see the output's header).
The tool refuses to write unless every copy carries the same two sheets, because the
game draws whichever copy is mounted first with this one table.
"""
import hashlib
import json
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import sourceassets  # noqa: E402
import sparkleshape  # noqa: E402  (its DXT5 decoder)
import vtfsheet  # noqa: E402

SMOKE1 = 'materials/particle/smoke1/smoke1.vtf'
VISTA = 'materials/particle/vistasmokev1/vistasmokev1.vtf'


def sequences(sheet):
    seqs = sheet['sequences']
    return [seqs[k] for k in sorted(seqs)] if isinstance(seqs, dict) else seqs


def one_uv(frame):
    uv = frame['uv']
    if any(channel != uv[0] for channel in uv):
        raise SystemExit('a frame whose four UV channels differ is not supported')
    return tuple(uv[0])


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    copies = []
    for arg in sys.argv[1:]:
        src = sourceassets.VpkSource(arg)
        if SMOKE1 not in src.entries or VISTA not in src.entries:
            raise SystemExit('%s: does not carry both smoke sheets' % arg)
        s1, vs = src.read(SMOKE1).data, src.read(VISTA).data
        sheets = (vtfsheet.read_sheet(s1), vtfsheet.read_sheet(vs))
        if None in sheets:
            raise SystemExit('%s: a smoke texture with no sheet resource' % arg)
        canon = hashlib.sha256(json.dumps(sheets, sort_keys=True).encode()).hexdigest()
        copies.append((arg, canon, sheets, vs, hashlib.sha256(s1).hexdigest(), hashlib.sha256(vs).hexdigest()))
    if len({c[1] for c in copies}) != 1:
        raise SystemExit('the copies disagree about the sheets:\n' + '\n'.join('  %s  %s' % (c[0], c[1][:16]) for c in copies))
    smoke1, vista = (sequences(s) for s in copies[0][2])

    # smoke1: sixteen one-frame sequences over six pictures in a row.
    cells = sorted({one_uv(q['frames'][0]) for q in smoke1})
    if len(cells) != 6 or any(len(q['frames']) != 1 for q in smoke1):
        raise SystemExit('smoke1 is not six single pictures any more: %d cells' % len(cells))
    stride = cells[1][0] - cells[0][0]
    if any(abs((cells[i + 1][0] - cells[i][0]) - stride) > 1e-4 or cells[i][1] != cells[0][1] for i in range(5)):
        raise SystemExit('smoke1\'s six pictures are not one evenly spaced row')

    # vistasmokev1: sequences 0-3 are the alpha (16 frames; 2 repeats 0, 3 repeats 1),
    # 4-9 the colour the material lays under it ($sequence_blend_mode 1).
    for a, b in ((0, 2), (1, 3)):
        if [one_uv(f) for f in vista[a]['frames']] != [one_uv(f) for f in vista[b]['frames']]:
            raise SystemExit('vistasmokev1 sequence %d no longer repeats sequence %d' % (b, a))
    # The largest mip is the last thing in the file (the sheet sits between header and image).
    data = copies[0][3]
    w, h = struct.unpack_from('<HH', data, 16)
    if struct.unpack_from('<i', data, 52)[0] != 15 or struct.unpack_from('<H', data, 24)[0] != 1:
        raise SystemExit('vistasmokev1 is not one DXT5 frame any more')
    px = sparkleshape.dxt5(data[len(data) - (w // 4) * (h // 4) * 16:], w, h)
    acc = [0, 0, 0]
    n = 0
    for q in vista[4:10]:
        for f in q['frames']:
            s1, t1, s2, t2 = one_uv(f)
            for y in range(int(t1 * h), int(t2 * h), 4):
                row = px[y]
                for x in range(int(s1 * w), int(s2 * w), 4):
                    p = row[x]
                    acc[0] += p[0]
                    acc[1] += p[1]
                    acc[2] += p[2]
                    n += 1
    grey = [c / (255.0 * n) for c in acc]

    sys.stdout.reconfigure(newline='\n')   # the repo is LF; a redirect on Windows would write CRLF
    w_ = sys.stdout.write
    w_('// GENERATED by tools/smokesheet.py -- do not edit; run the tool again.\n')
    w_('// particle/smoke1/smoke1.vtf and particle/vistasmokev1/vistasmokev1.vtf, sheet resource 0x10.\n')
    w_('// Sheets sha256 %s, the same in every copy read:\n' % copies[0][1][:16])
    for c in copies:
        w_('//   smoke1 %s  vistasmokev1 %s\n' % (c[4][:16], c[5][:16]))
    w_('// SMV_GREY is measured, not copied: the mean colour of vistasmokev1\'s sequences 4-9, which\n')
    w_('// its material draws under the alpha of sequences 0-3.  A flat stand-in for that picture.\n\n')
    c0 = cells[0]
    w_('// smoke1\'s six pictures: tcoords of the first, then "1 6 <stride>" picks one at random.\n')
    w_('#define SM1_TCOORDS "%.6g %.6g %.6g %.6g 1 6 %.6g"\n' % (c0[0], c0[1], c0[2], c0[3], stride))
    w_('#define SM1_CELL    %.6g\n' % (c0[2] - c0[0]))
    v0 = one_uv(vista[0]['frames'][0])
    w_('#define SMV_CELL    %.6g\n' % (v0[2] - v0[0]))
    w_('#define SMV_GREY    "%.3f, %.3f, %.3f"\n\n' % tuple(grey))
    w_('// vistasmokev1 sequence 0 or 1: "texframe <duration> s1 t1 s2 t2" for its %d frames.\n' % len(vista[0]['frames']))
    w_('string(float seq) Emit_VistaRows =\n{\n')
    for i in (0, 1):
        w_('\tif (seq == %d) return\n' % i)
        w_('\n'.join('\t\t"texframe %.9g %.6g %.6g %.6g %.6g\\n"' % ((f['duration'],) + tuple(one_uv(f)))
                     for f in vista[i]['frames']) + ';\n')
    w_('\treturn "";\n};\n')


if __name__ == '__main__':
    main()
