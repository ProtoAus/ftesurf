#!/usr/bin/env python3
"""Write src/client/cl_flamesheet.qc: the frame rectangles of Source's env_fire atlas.

    python tools/flamesheet.py <fire_burning_character.vtf> [more copies...] > src/client/cl_flamesheet.qc

The atlas is particle/fire_burning_character/fire_burning_character.vtf, which every
env_fire_* system in particles/fire_01.pcf draws through fire_env_fire.vmt.  Its sheet
(VTF resource 0x10) is read with tools/vtfsheet.py; nothing of the image is copied.
Pass every copy you have (Half-Life 2, Counter-Strike: Source, Momentum's mount): the
tool refuses to write unless all of them carry the same sheet, because the game draws
whichever copy is mounted first with this one table.
"""
import hashlib
import json
import sys

import vtfsheet


def rows(seq, flip):
    out = []
    for frame in seq['frames']:
        uv = frame['uv']
        if any(channel != uv[0] for channel in uv):
            raise SystemExit('a frame whose four UV channels differ is not supported')
        s1, t1, s2, t2 = uv[0]
        if flip:
            s1, s2 = s2, s1
        out.append('texframe %.9g %.6g %.6g %.6g %.6g' % (frame['duration'], s1, t1, s2, t2))
    return out


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    sheets = []
    for path in sys.argv[1:]:
        data = open(path, 'rb').read()
        sheet = vtfsheet.read_sheet(data)
        if sheet is None:
            raise SystemExit('%s: no sheet resource' % path)
        canon = json.dumps(sheet, sort_keys=True)
        sheets.append((path, len(data), hashlib.sha256(data).hexdigest(),
                       hashlib.sha256(canon.encode()).hexdigest(), sheet))
    if len({s[3] for s in sheets}) != 1:
        raise SystemExit('the copies disagree about the sheet:\n' +
                         '\n'.join('  %s  sheet %s' % (s[0], s[3][:16]) for s in sheets))
    sheet = sheets[0][4]
    seqs = sheet['sequences']
    seqs = [seqs[k] for k in sorted(seqs)] if isinstance(seqs, dict) else seqs

    sys.stdout.reconfigure(newline='\n')   # the repo is LF; a redirect on Windows would write CRLF
    w = sys.stdout.write
    w('// GENERATED by tools/flamesheet.py -- do not edit; run the tool again.\n')
    w('// particle/fire_burning_character/fire_burning_character.vtf, sheet resource 0x10.\n')
    w('// Sheet sha256 %s, the same in every copy read:\n' % sheets[0][3][:16])
    for path, size, sha, _, _ in sheets:
        w('//   %d bytes, file sha256 %s\n' % (size, sha[:16]))
    w('// Sequences 0-2 are the short wide flames (env_fire_*_b), 3-5 the tall ones.\n\n')
    w('float(float seq) Emit_FlameFrames =\n{\n')
    for i, seq in enumerate(seqs):
        w('\tif (seq == %d) return %d;\n' % (i, len(seq['frames'])))
    w('\treturn 0;\n};\n\n')
    w('// "texframe <duration> s1 t1 s2 t2" for every frame; flip mirrors the frame.\n')
    w('string(float seq, float flip) Emit_FlameRows =\n{\n')
    for flip in (0, 1):
        w('\tif (%sflip)\n\t{\n' % ('' if flip else '!'))
        for i, seq in enumerate(seqs):
            w('\t\tif (seq == %d) return\n' % i)
            w('\n'.join('\t\t\t"%s\\n"' % r for r in rows(seq, flip)) + ';\n')
        w('\t}\n')
    w('\treturn "";\n};\n')


if __name__ == '__main__':
    main()
